"""An F-test takes its direction from the contrasts that come from it.

Every factor in the factorial designs this reads has two levels, so each F-test has one degree of freedom: a main
effect is the same comparison as its main-effect contrast, and the interaction is the difference between the two
simple effects.
"""

import csv

from evidome.enrich import read_comparison
from test_gene_sets_are_indexed_to_human_ensembl import sources  # noqa: F401  (fixture)
from evidome.wide_stats import DIRECTION_ROLE, read_wide_statistics

HEADER = """# generated by paralome 0.5
#   diet_WD_vs_CD: ANOVA F-test (main effect/interaction) -- no single direction
#   MET_vs_VEH: ANOVA F-test (main effect/interaction) -- no single direction
#   diet_x_drug: ANOVA F-test (main effect/interaction) -- no single direction
#   orphan_A_vs_B: ANOVA F-test (main effect/interaction) -- no single direction
"""
CONTRASTS = ["WD_vs_CD_main_effect", "MET_vs_VEH_main_effect", "WD_vs_CD_within_VEH_contrast",
             "WD_vs_CD_within_MET_contrast"]
FTESTS = ["diet_WD_vs_CD", "MET_vs_VEH", "diet_x_drug", "orphan_A_vs_B"]


def _table(tmp_path, effects):
    """effects: contrast -> per-gene Effect values (two genes)."""
    cols = ["Gene"]
    for f in FTESTS:
        cols += [f"{f}_F", f"{f}_ANOVA_p", f"{f}_ANOVA_q"]
    for c in CONTRASTS:
        cols += [f"{c}_Raw_FPKM_Control_mean", f"{c}_Raw_FPKM_Treatment_mean", f"{c}_Fold_change", f"{c}_Effect",
                 f"{c}_T-statistic", f"{c}_P-value", f"{c}_Q-value"]
    rows = []
    for g in range(2):
        row = [f"ENSMMUG{g}"]
        for _ in FTESTS:
            row += ["5", "0.01", "0.05"]
        for c in CONTRASTS:
            e = effects[c][g]
            row += ["1", "2", "2", str(e), str(e * 3), "0.01", "0.05"]
        rows.append(",".join(row))
    path = tmp_path / "stats.csv"
    path.write_text(HEADER + ",".join(cols) + "\n" + "\n".join(rows) + "\n")
    return read_wide_statistics(path)


EFFECTS = {"WD_vs_CD_main_effect": [1.5, -0.5], "MET_vs_VEH_main_effect": [-2.0, 0.3],
           "WD_vs_CD_within_VEH_contrast": [1.0, 0.2], "WD_vs_CD_within_MET_contrast": [2.0, -1.2]}


def test_main_effects_take_their_main_effect_contrast(tmp_path):
    table = _table(tmp_path, EFFECTS)
    by = {c.name: c for c in table.comparisons}
    assert by["diet_WD_vs_CD"].direction_from == "WD_vs_CD_main_effect (Effect)"      # <factor>_<alt>_vs_<ref>
    assert by["MET_vs_VEH"].direction_from == "MET_vs_VEH_main_effect (Effect)"         # label without the factor
    assert table.column(by["diet_WD_vs_CD"], DIRECTION_ROLE) == [1.5, -0.5]
    assert table.column(by["MET_vs_VEH"], DIRECTION_ROLE) == [-2.0, 0.3]


def test_the_interaction_is_the_difference_of_its_simple_effects(tmp_path):
    table = _table(tmp_path, EFFECTS)
    inter = {c.name: c for c in table.comparisons}["diet_x_drug"]
    assert inter.direction_from == ("WD_vs_CD_within_MET_contrast (Effect) minus "
                                    "WD_vs_CD_within_VEH_contrast (Effect)")
    assert [round(v, 6) for v in table.column(inter, DIRECTION_ROLE)] == [1.0, -1.4]


def test_an_f_test_without_its_contrasts_keeps_no_direction(tmp_path):
    table = _table(tmp_path, EFFECTS)
    orphan = {c.name: c for c in table.comparisons}["orphan_A_vs_B"]
    assert orphan.direction_from is None and DIRECTION_ROLE not in orphan.columns


def test_a_directed_f_test_is_ranked_and_split_up_and_down(tmp_path):
    path = tmp_path / "F.human_genes.csv"
    with path.open("w", newline="") as h:
        w = csv.writer(h)
        w.writerow(["human_gene_id", "human_symbol", "tested", "F", "ANOVA_p", "ANOVA_q", DIRECTION_ROLE])
        w.writerows([["ENSG1", "A", "yes", "9", "0.001", "0.01", "1.5"],
                     ["ENSG2", "B", "yes", "4", "0.01", "0.05", "-0.7"],
                     ["ENSG3", "C", "yes", "1", "0.5", "0.6", ""]])
    t = read_comparison(path, "F", "ftest")
    assert t.direction == {"ENSG1": 1, "ENSG2": -1, "ENSG3": 0}
    assert round(t.metric["ENSG1"], 6) == 3.0 and round(t.metric["ENSG2"], 6) == -2.0
    assert t.metric_name == "sign(Direction_estimate) x -log10(ANOVA p)"


def test_end_to_end_a_directed_f_test_gets_up_down_ora_gsea_regulator_z_and_a_figure(sources, tmp_path):
    import json

    from evidome.cli import main
    from evidome.genesets import fetch_genesets
    from evidome.regulators import fetch_regulators
    from test_evidence_bundle_describes_itself import COLLECTRI, SIGNALLING, TABLE

    ref, urls = sources
    fetch_genesets(ref, urls=urls, threads=1, log=lambda *_: None)
    (tmp_path / "c.tsv").write_text(COLLECTRI)
    (tmp_path / "s.tsv").write_text(SIGNALLING)
    fetch_regulators(ref, urls={"collectri": (tmp_path / "c.tsv").as_uri(), "omnipath": (tmp_path / "s.tsv").as_uri()},
                     threads=1, log=lambda *_: None)
    # the fixture's contrast A becomes a main-effect contrast, and its F-test the matching main effect
    text = TABLE.replace("#   A: control", "#   WD_vs_CD_main_effect: control").replace(",A_", ",WD_vs_CD_main_effect_")
    text = text.replace("#   F1: ANOVA", "#   diet_WD_vs_CD: ANOVA").replace(",F1_", ",diet_WD_vs_CD_")
    table = tmp_path / "stats.csv"
    table.write_text(text)
    out = tmp_path / "study"
    assert main([str(table), "--out", str(out), "--reference-dir", str(ref), "--threads", "1",
                 "--min-species-match", "0.5", "--min-size", "1", "--permutations", "100",
                 "--max-permutations", "1000", "--min-targets", "2", "--figure-formats", "svg",
                 "--keep-duplicate-ftests"]) == 0
    summary = {c["comparison"]: c for c in json.loads((out / "comparison_summary.json").read_text())["comparisons"]}
    assert summary["diet_WD_vs_CD"]["direction_from"] == "WD_vs_CD_main_effect (T-statistic)"
    ora = list(csv.DictReader((out / "enrichment/diet_WD_vs_CD/ora.csv").open()))
    assert {r["direction"] for r in ora} == {"up", "down", "all"}
    assert (out / "enrichment/diet_WD_vs_CD/gsea.csv").exists()
    regs = list(csv.DictReader((out / "regulators/diet_WD_vs_CD/regulators.csv").open()))
    assert any(r["activation_z"] for r in regs)
    human = next(csv.DictReader((out / "comparisons/diet_WD_vs_CD.human_genes.csv").open()))
    assert DIRECTION_ROLE in human


def test_a_main_effect_f_test_is_skipped_for_its_contrast_and_the_interaction_kept(tmp_path):
    from evidome.wide_stats import drop_duplicate_ftests

    table = _table(tmp_path, EFFECTS)
    dropped = drop_duplicate_ftests(table)
    assert dropped == [("diet_WD_vs_CD", "WD_vs_CD_main_effect"), ("MET_vs_VEH", "MET_vs_VEH_main_effect")]
    names = [c.name for c in table.comparisons]
    assert "diet_x_drug" in names and "orphan_A_vs_B" in names and "diet_WD_vs_CD" not in names
    assert any("analysed in its place" in n for n in table.notes)
