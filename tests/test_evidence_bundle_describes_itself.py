def test_every_described_column_is_one_the_program_writes_or_documents():
    """COLUMN_TEXT is the single description source; the report refuses undescribed columns (EVD-0024)."""
    from evidome.crosswalk import CROSSWALK_COLUMNS
    from evidome.enrich import GSEA_COLUMNS, ORA_COLUMNS
    from evidome.human_tables import BALLOT_COLUMNS, HUMAN_TABLE_IDENTITY

    for columns in (CROSSWALK_COLUMNS, ORA_COLUMNS, GSEA_COLUMNS, BALLOT_COLUMNS, HUMAN_TABLE_IDENTITY):
        assert set(columns) <= set(COLUMN_TEXT), set(columns) - set(COLUMN_TEXT)


