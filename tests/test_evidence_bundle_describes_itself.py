def test_regulators_reach_the_bundle(run):
    paths = build_report(run, log=lambda *_: None)
    regs = list(csv.DictReader((paths["evidence"] / "regulators.csv").open()))
    assert {(r["comparison"], r["network"], r["regulator"]) for r in regs} >= {
        ("A", "collectri", "PAR9"), ("A", "signalling_via_tf", "KIN"), ("F1", "collectri", "PAR9")}
    par9 = [r for r in regs if r["comparison"] == "A" and r["regulator"] == "PAR9"][0]
    assert par9["targets_in_universe"] != "" and par9["activity_t"] != ""
    kin = [r for r in regs if r["comparison"] == "A" and r["regulator"] == "KIN"][0]
    assert kin["via_tfs"] == "PAR9" and kin["bias_term"] != ""
    manifest = json.loads(paths["manifest"].read_text())
    assert "license=commercial" in manifest["provenance"]["regulator_data"]["files"]["collectri"]["url"] or \
        manifest["provenance"]["regulator_data"]["licence"].startswith("OmniPath")
