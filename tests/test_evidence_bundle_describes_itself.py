def test_every_file_is_indexed_and_every_column_described(run):
    paths = build_report(run, log=lambda *_: None)
    manifest = json.loads(paths["manifest"].read_text())
    assert manifest["schema"].endswith(".evidence.v1") and manifest["program_version"]
    assert [f["path"] for f in manifest["files"]] == list(FILES)
    for f in manifest["files"]:
        header = next(csv.reader((paths["evidence"] / f["path"]).open()))
        assert header == [c["name"] for c in f["columns"]]
        assert all(c["description"] for c in f["columns"])
        assert f["rows"] == sum(1 for _ in (paths["evidence"] / f["path"]).open()) - 1
    assert manifest["provenance"]["species"] == M and manifest["provenance"]["gene_sets"]["licences"]
    assert manifest["reading_guide"] and manifest["glossary"]["ORA"]


def test_the_long_tables_carry_every_comparison(run):
    paths = build_report(run, log=lambda *_: None)
    ev = paths["evidence"]
    stats = list(csv.DictReader((ev / "human_gene_statistics.csv").open()))
    assert {r["comparison"] for r in stats} == {"A", "F1"}
    a = [r for r in stats if r["comparison"] == "A" and r["human_symbol"] == "TSPAN6"][0]
    assert a["P-value"] == "0.001" and a["ANOVA_p"] == ""            # union of statistic columns
    comps = {r["comparison"]: r for r in csv.DictReader((ev / "comparisons.csv").open())}
    assert comps["A"]["treatment"] == "WD" and comps["F1"]["kind"] == "ftest"
    assert comps["A"]["gsea_rank_metric"] == "T-statistic" and comps["F1"]["gsea_rank_metric"] == ""
    ora = list(csv.DictReader((ev / "enrichment_ora.csv").open()))
    assert {r["comparison"] for r in ora} == {"A", "F1"} and {r["direction"] for r in ora if r["comparison"] == "F1"} == {"all"}


def test_findings_are_exactly_the_q_below_threshold_rows_ranked(run):
    paths = build_report(run, log=lambda *_: None)
    ev = paths["evidence"]
    findings = list(csv.DictReader((ev / "findings.csv").open()))
    ora_q = [r for r in csv.DictReader((ev / "enrichment_ora.csv").open()) if float(r["q"]) < 0.05]
    gsea_q = [r for r in csv.DictReader((ev / "enrichment_gsea.csv").open()) if float(r["q"]) < 0.05]
    regs = list(csv.DictReader((ev / "regulators.csv").open()))
    reg_activity = [r for r in regs if r["activity_q"] and float(r["activity_q"]) < 0.05]
    reg_overlap = [r for r in regs if float(r["overlap_q"]) < 0.05]
    assert len(findings) == len(ora_q) + len(gsea_q) + len(reg_activity) + len(reg_overlap)
    assert sum(f["method"] == "REGULATOR_OVERLAP" for f in findings) == len(reg_overlap) > 0
    for key in {(f["comparison"], f["method"], f["direction"], f["source"]) for f in findings}:
        group = [f for f in findings if (f["comparison"], f["method"], f["direction"], f["source"]) == key]
        assert [int(f["rank"]) for f in group] == list(range(1, len(group) + 1))
        assert [float(f["q"]) for f in group] == sorted(float(f["q"]) for f in group)


