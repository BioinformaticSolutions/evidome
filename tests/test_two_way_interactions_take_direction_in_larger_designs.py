"""A two-way interaction F-test takes its direction in a design of more than two factors.

In a 2x2x2x2 study (Paralome anova:cell) every interaction F-test came out with no direction, so no GSEA
and no activation z. The two-factor rule looked for a factor with exactly two "within" contrasts; Paralome
(0.5.dev87+) writes a factor's contrasts within each level of each other factor, and of each combination, so a
factor has many. The two the A x B interaction needs -- A within B's levels alone, averaged over the rest -- are
now looked up by exact name. Three-way interactions have no single direction and keep none.
"""

from evidome.wide_stats import DIRECTION_ROLE, read_wide_statistics

# diet (WD vs CD, F named <factor>_<stem>), NICD (NICD vs CTRL, F named by its levels alone: the factor is in
# the header line), time (4D vs 2D)
FTESTS = {
    "diet_WD_vs_CD": "ANOVA F-test, main effect of diet (WD versus CD)",
    "NICD_vs_CTRL": "ANOVA F-test, main effect of NICD (NICD versus CTRL)",
    "time_4D_vs_2D": "ANOVA F-test, main effect of time (4D versus 2D)",
    "diet_x_NICD": "ANOVA F-test, interaction of diet and NICD",
    "diet_x_time": "ANOVA F-test, interaction of diet and time",
    "NICD_x_time": "ANOVA F-test, interaction of NICD and time",
    "diet_x_NICD_x_time": "ANOVA F-test, interaction of diet, NICD and time",
}
STEMS = {"WD_vs_CD": ("NICD", "CTRL", "4D", "2D"), "NICD_vs_CTRL": ("WD", "CD", "4D", "2D"),
         "4D_vs_2D": ("WD", "CD", "NICD", "CTRL")}


def _contrasts():
    names = []
    for stem, (b1, b2, c1, c2) in STEMS.items():
        names.append(f"{stem}_main_effect")
        names += [f"{stem}_within_{level}_contrast" for level in (b1, b2, c1, c2)]
        names += [f"{stem}_within_{x}_{y}_contrast" for x in (b1, b2) for y in (c1, c2)]
    return names


def _table(tmp_path):
    contrasts = _contrasts()
    effect = {name: [round(0.1 * (i + 1), 1), round(-0.05 * (i + 1), 2)] for i, name in enumerate(contrasts)}
    header = "# generated by paralome 0.5.dev91\n# comparisons in this file:\n" + "".join(
        f"#   {name}: {text}\n" for name, text in FTESTS.items()) + "".join(
        f"#   {name}: ANOVA contrast\n" for name in contrasts)
    cols = ["Gene"] + [f"{f}_{r}" for f in FTESTS for r in ("F", "ANOVA_p", "ANOVA_q")] + [
        f"{c}_{r}" for c in contrasts for r in ("Log2_fold_change", "Effect", "T-statistic", "P-value", "Q-value")]
    rows = []
    for g in range(2):
        row = [f"ENSMUSG0000000000{g}"] + ["5", "0.01", "0.05"] * len(FTESTS)
        for c in contrasts:
            e = effect[c][g]
            row += [str(e), str(e), str(e * 3), "0.01", "0.05"]
        rows.append(",".join(row))
    path = tmp_path / "stats.csv"
    path.write_text(header + ",".join(cols) + "\n" + "\n".join(rows) + "\n")
    return read_wide_statistics(path), effect


def test_each_two_way_interaction_is_its_own_difference_of_simple_effects(tmp_path):
    table, effect = _table(tmp_path)
    by = {c.name: c for c in table.comparisons}

    def expected(hi, lo):
        return [round(a - b, 10) for a, b in zip(effect[hi], effect[lo])]

    pairs = {
        "diet_x_NICD": ("NICD_vs_CTRL_within_WD_contrast", "NICD_vs_CTRL_within_CD_contrast"),
        "diet_x_time": ("4D_vs_2D_within_WD_contrast", "4D_vs_2D_within_CD_contrast"),
        "NICD_x_time": ("4D_vs_2D_within_NICD_contrast", "4D_vs_2D_within_CTRL_contrast"),
    }
    for ftest, (hi, lo) in pairs.items():
        assert by[ftest].direction_from == f"{hi} (Effect) minus {lo} (Effect)", ftest
        got = [round(v, 10) for v in table.column(by[ftest], DIRECTION_ROLE)]
        assert got == expected(hi, lo), ftest


def test_a_three_way_interaction_keeps_no_direction(tmp_path):
    table, _ = _table(tmp_path)
    three = {c.name: c for c in table.comparisons}["diet_x_NICD_x_time"]
    assert three.direction_from is None and DIRECTION_ROLE not in three.columns


def test_the_main_effects_are_as_before(tmp_path):
    table, _ = _table(tmp_path)
    by = {c.name: c for c in table.comparisons}
    assert by["diet_WD_vs_CD"].direction_from == "WD_vs_CD_main_effect (Effect)"
    assert by["NICD_vs_CTRL"].direction_from == "NICD_vs_CTRL_main_effect (Effect)"
