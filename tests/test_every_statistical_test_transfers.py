"""Whatever test produced a comparison, the table transfers intact.

Paralome writes different columns for different tests: a plain t-test slice
has no Effect or T-statistic, an ANOVA model contrast has both, an F-test has
no direction at all, and outputs that are not bulk FPKM (single-cell
pseudobulk, accessibility) carry their group means as Control_mean /
Treatment_mean rather than Raw_FPKM_*. Every shape is read, nothing is
guessed, and a half-written block is refused.
"""

import pytest

from evidome.errors import ProjectError
from evidome.human_tables import stat_roles
from evidome.wide_stats import read_wide_statistics


def _write(tmp_path, header, columns, rows):
    path = tmp_path / "stats.csv"
    path.write_text(header + ",".join(columns) + "\n" + "\n".join(rows) + "\n")
    return path


def _block(name, means, extra=()):
    return [f"{name}_{m}" for m in means] + [f"{name}_Fold_change"] + [f"{name}_{e}" for e in extra] + \
           [f"{name}_P-value", f"{name}_Q-value"]


FPKM = ("Raw_FPKM_Control_mean", "Raw_FPKM_Treatment_mean")
OTHER = ("Control_mean", "Treatment_mean")


def test_pairwise_header_names_its_arms(tmp_path):
    header = "# generated by paralome 0.5\n#   WD_vs_CD: pairwise, control=CD, treatment=WD\n"
    path = _write(tmp_path, header, ["Gene", "Common_name"] + _block("WD_vs_CD", FPKM),
                  ["ENSMMUG1,A,1,2,2,0.01,0.1"])
    table = read_wide_statistics(path)
    comp = table.comparisons[0]
    assert (comp.control, comp.treatment) == ("CD", "WD")
    assert table.notes == []


def test_described_contrast_without_arms_is_not_reported_as_undescribed(tmp_path):
    header = "#   M_main_effect: ANOVA model contrast (pooled-error estimate, not an independent t-test)\n"
    path = _write(tmp_path, header, ["Gene"] + _block("M_main_effect", FPKM, ("Effect", "T-statistic")),
                  ["ENSMMUG1,1,2,2,1.0,3.1,0.01,0.1"])
    table = read_wide_statistics(path)
    assert table.comparisons[0].control is None
    assert table.notes == []


def test_non_fpkm_means_are_accepted_and_kept_under_their_own_names(tmp_path):
    header = "#   B_cells__pseudobulk_t: control=CD, treatment=WD\n"
    path = _write(tmp_path, header, ["Gene", "Common_name"] + _block("B_cells__pseudobulk_t", OTHER, ("T-statistic",)),
                  ["ENSMMUG1,A,5,10,2,2.5,0.01,0.1"])
    table = read_wide_statistics(path)
    comp = table.comparisons[0]
    assert set(comp.columns) == {"Control_mean", "Treatment_mean", "Fold_change", "T-statistic", "P-value", "Q-value"}
    assert stat_roles("contrast", comp.columns) == ["Control_mean", "Treatment_mean", "Fold_change", "P-value",
                                                    "Q-value", "T-statistic"]


def test_bulk_column_order_is_unchanged(tmp_path):
    path = _write(tmp_path, "", ["Gene"] + _block("X", FPKM, ("Effect", "T-statistic")), ["ENSMMUG1,1,2,2,1,3,0.01,0.1"])
    comp = read_wide_statistics(path).comparisons[0]
    assert stat_roles("contrast", comp.columns) == ["Raw_FPKM_Control_mean", "Raw_FPKM_Treatment_mean", "Fold_change",
                                                    "P-value", "Q-value", "Effect", "T-statistic"]


@pytest.mark.parametrize("means, missing", [
    (("Control_mean",), "X_Treatment_mean"),
    (("Raw_FPKM_Treatment_mean",), "X_Raw_FPKM_Control_mean"),
])
def test_a_block_with_half_a_pair_of_means_is_refused(tmp_path, means, missing):
    cols = ["Gene"] + _block("X", means)
    path = _write(tmp_path, "", cols, ["ENSMMUG1," + ",".join(["1"] * (len(cols) - 1))])
    with pytest.raises(ProjectError) as err:
        read_wide_statistics(path)
    assert err.value.code == 6 and missing in str(err.value)


def test_a_block_with_no_means_is_read_since_means_are_optional(tmp_path):
    # a burden test has no group means; the means never enter a statistic
    path = _write(tmp_path, "", ["Gene"] + _block("X", ()), ["ENSMMUG1,2,0.01,0.1"])
    comp = read_wide_statistics(path).comparisons[0]
    assert stat_roles("contrast", comp.columns) == ["Fold_change", "P-value", "Q-value"]
