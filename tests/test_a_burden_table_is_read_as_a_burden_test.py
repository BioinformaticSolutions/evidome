def test_an_infinite_log2_is_a_fold_change_and_is_accepted(tmp_path):
    rows = [("ENSG00000000001", "TSPAN6", "inf", 0.001, 0.01, "-inf", 0.5, 0.6)]
    table = read_wide_statistics(_burden_table(tmp_path / "t.tsv", rows=rows))
    assert table.column(table.comparisons[0], "Log2_fold_change") == [float("inf")]


def _human_table(path, role, values):
    with path.open("w", newline="") as h:
        w = csv.writer(h)
        w.writerow(["human_gene_id", "human_symbol", "tested", role, "P-value", "Q-value"])
        for i, v in enumerate(values):
            w.writerow([f"ENSG{i:011d}", f"G{i}", "yes", v, 0.01, 0.1])
    return path


def test_a_declared_log2_column_is_not_re_guessed_even_when_every_value_is_between_0_and_1(tmp_path):
    values = [0.2, 0.5, 0.9, 0.3]
    log2 = read_comparison(_human_table(tmp_path / "a.csv", "Log2_fold_change", values), "a", "burden")
    assert log2.direction_from == "Log2_fold_change"
    assert set(log2.direction.values()) == {1}                   # all more than expected: all up
    assert log2.metric_name == "sign(Log2_fold_change) x -log10(p)"
    # the same numbers in an undeclared Fold_change column are judged ratios below 1: down (unchanged rule)
    guessed = read_comparison(_human_table(tmp_path / "b.csv", "Fold_change", values), "b", "contrast")
    assert guessed.direction_from == "Fold_change (ratio)" and set(guessed.direction.values()) == {-1}
    # exactly 1.0 in log2 is a doubling, not "unchanged"
    one = read_comparison(_human_table(tmp_path / "c.csv", "Log2_fold_change", [1.0, -1.0]), "c", "burden")
    assert sorted(one.direction.values()) == [-1, 1]


def test_a_collision_votes_on_the_size_of_a_log2_change():
    ballot = resolve("H", "dominant_ptv", "burden", {
        "a": {"P-value": 0.01, "Log2_fold_change": 0.3},
        "b": {"P-value": 0.02, "Log2_fold_change": -2.0}})
    assert ballot.picks == {"P-value": "a", "Log2_fold_change": "b"}
    assert ballot.tie and ballot.winner == "a"                    # 1-1: the tie-break is the smaller p


def test_a_folder_of_burden_tables_keeps_the_test_when_combined(tmp_path):
    folder = tmp_path / "in"
    folder.mkdir()
    (folder / "dominant_ptv.csv").write_text("# dominant_ptv: control=gnomAD, treatment=probands, test=burden\n"
                                             "gene_id\tgene_name\tLog2_fold_change\tP-value\tQ-value\n"
                                             "ENSG00000000001\tTSPAN6\t0.4\t0.01\t0.1\n")
    out = combine([folder / "dominant_ptv.csv"], tmp_path / "wide.csv", log=lambda *_: None)
    [comp] = read_wide_statistics(out).comparisons
    assert (comp.kind, comp.control, comp.treatment) == ("burden", "gnomAD", "probands")
    assert set(comp.columns) == {"Log2_fold_change", "P-value", "Q-value"}


def _regulators(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as h:
        w = csv.DictWriter(h, REGULATOR_COLUMNS, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def test_a_one_sided_burden_result_is_still_drawn(tmp_path):
    d = tmp_path / "study"
    _regulators(d / "regulators/dominant_ptv/regulators.csv",
                [{"network": "collectri", "regulator": f"UP{i}", "overlap_p": 10 ** -(5 + i), "activation_z": 2 + i}
                 for i in range(3)])
    # a contrast keeps as many bars on each side as the shorter side has: none
    assert panels_for(d, "dominant_ptv", 25) == []
    [panel] = panels_for(d, "dominant_ptv", 25, kind="burden")
    assert panel.left == [] and [i.label for i in panel.right] == ["UP2", "UP1", "UP0"]
    if figures.available():
        written = draw(panel, tmp_path / "figs", FigureSettings(formats=("svg",)), version="t")
        assert {p.suffix for p in written} == {".svg", ".csv"}
        assert "UP2" in (tmp_path / "figs/dominant_ptv_regulators.svg").read_text()


OPTS = ["--threads", "1", "--min-species-match", "0.5", "--min-size", "1", "--permutations", "100",
        "--max-permutations", "1000", "--min-targets", "2", "--figure-formats", "svg"]


@pytest.fixture
def burden_run(sources, tmp_path):
    from evidome.genesets import fetch_genesets
    from evidome.regulators import fetch_regulators

    ref, urls = sources
    fetch_genesets(ref, urls=urls, threads=1, log=lambda *_: None)
    (tmp_path / "c.tsv").write_text(COLLECTRI)
    (tmp_path / "s.tsv").write_text(SIGNALLING)
    fetch_regulators(ref, urls={"collectri": (tmp_path / "c.tsv").as_uri(), "omnipath": (tmp_path / "s.tsv").as_uri()},
                     threads=1, log=lambda *_: None)
    out = tmp_path / "burden_evidence"
    table = _burden_table(tmp_path / "gene_burden.tsv")
    assert main([str(table), "--out", str(out), "--reference-dir", str(ref)] + OPTS) == 0
    return out


def test_a_burden_table_runs_end_to_end_through_the_crosswalk(burden_run):
    out = burden_run
    summary = json.loads((out / "comparison_summary.json").read_text())
    assert [(c["comparison"], c["kind"], c["control"], c["treatment"]) for c in summary["comparisons"]] == \
        [(c, "burden", "gnomAD", "probands") for c in COMPARISONS]
    with (out / "comparisons/dominant_ptv.human_genes.csv").open() as h:
        rows = {r["human_gene_id"]: r for r in csv.DictReader(h)}
    header = set(next(iter(rows.values())))
    assert "Log2_fold_change" in header and "Fold_change" not in header and "Control_mean" not in header
    assert rows["ENSG00000000004"]["Log2_fold_change"] == "-0.5" and rows["ENSG00000000004"]["tested"] == "yes"

    enrichment = json.loads((out / "enrichment/enrichment.json").read_text())
    by = {c["comparison"]: c for c in enrichment["comparisons"]}
    assert by["recessive_ptv"]["kind"] == "burden"
    # no GSEA for a burden test (its ranking is confounded with detectability), and it says why
    assert by["recessive_ptv"]["gsea"] is None and "detectability" in by["recessive_ptv"]["gsea_skipped"]
    assert "rank_metric" not in by["recessive_ptv"]
    # no Null_selection_probability in this table: the ORA is marked unadjusted
    assert by["recessive_ptv"]["ora_null"] == "hypergeometric (unadjusted for detectability)"
    with (out / "enrichment/recessive_ptv/ora.csv").open() as h:
        ora = list(csv.DictReader(h))
    # every recessive value is in (0, 1): every significant gene is up, none down
    assert {r["direction"] for r in ora} == {"up", "down", "all"}
    assert all(r["selected"] == "0" for r in ora if r["direction"] == "down")
    assert all(r["selected"] == "4" for r in ora if r["direction"] == "up")
    assert {r["null_model"] for r in ora} == {"hypergeometric (unadjusted for detectability)"}

    evidence = out / "evidence"
    with (evidence / "comparisons.csv").open() as h:
        assert {r["kind"] for r in csv.DictReader(h)} == {"burden"}
    manifest = json.loads((evidence / "manifest.json").read_text())
    assert "burden test" in manifest["glossary"]
    assert any("burden" in line for line in manifest["reading_guide"])
    with (evidence / "human_gene_statistics.csv").open() as h:
        columns = next(csv.reader(h))
    assert "Log2_fold_change" in columns and "Fold_change" not in columns and "Raw_FPKM_Control_mean" not in columns


def test_a_burden_figure_names_the_test(burden_run):
    if not figures.available():
        pytest.skip("matplotlib not installed")
    drawn = sorted(p.name for p in (burden_run / "figures").glob("*.svg"))
    assert drawn, "a burden comparison drew no figure"
    text = (burden_run / "figures" / drawn[0]).read_text()
    assert "burden test: probands vs gnomAD" in text
