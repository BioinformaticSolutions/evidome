COMPARISONS = ("dominant_ptv", "recessive_ptv")
HEADER = "".join(f"# {c}: control=gnomAD, treatment=probands, test=burden\n" for c in COMPARISONS)
COLUMNS = ["gene_id", "gene_name"] + [f"{c}_{r}" for c in COMPARISONS
                                      for r in ("Log2_fold_change", "P-value", "Q-value")]
# The fixture's human genes. dominant_ptv has negatives (fewer carriers than expected); every recessive_ptv value
# lies in (0, 1) -- the shape a guessed convention would read as ratios below 1, i.e. as down.
ROWS = [
    ("ENSG00000000001", "TSPAN6", 0.9, 0.001, 0.01, 0.4, 0.002, 0.02),
    ("ENSG00000000002", "PARA1", 1.6, 0.01, 0.05, 0.8, 0.01, 0.05),
    ("ENSG00000000004", "DUPA", -0.5, 0.3, 0.5, 0.2, 0.3, 0.5),
    ("ENSG00000000005", "DUPB", 0.7, 0.02, 0.08, 0.6, 0.02, 0.08),
    ("ENSG00000000007", "LINC0007", -1.2, 0.9, 0.9, ".", ".", "."),
    ("ENSG00000000009", "PAR9", 0.2, 0.5, 0.6, 0.1, 0.5, 0.6),
    ("ENSG00000000010", "H4C1", 0.3, 0.04, 0.1, 0.3, 0.04, 0.1),
]


def _burden_table(path, header=HEADER, columns=COLUMNS, rows=ROWS):
    lines = ["\t".join(columns)] + ["\t".join(str(v) for v in row) for row in rows]
    path.write_text("# generated by paralome 0.5.dev9 burden\n" + header + "\n".join(lines) + "\n")
    return path


def test_a_burden_table_is_read_as_burden_comparisons_with_no_means(tmp_path):
    table = read_wide_statistics(_burden_table(tmp_path / "burden.tsv"))
    assert table.id_column == "gene_id" and table.symbol_column == "gene_name"
    assert table.generator == "paralome 0.5.dev9 burden" and table.notes == []
    for comp in table.comparisons:
        assert (comp.kind, comp.control, comp.treatment) == ("burden", "gnomAD", "probands")
        assert stat_roles(comp.kind, comp.columns) == ["Log2_fold_change", "P-value", "Q-value"]
        assert comp.p_role == "P-value" and comp.fold_change_role == "Log2_fold_change"
    dom, rec = table.comparisons
    assert table.column(dom, "Log2_fold_change")[2] == -0.5
    assert rec.tested == 6 and table.column(rec, "Log2_fold_change")[4] is None


def test_a_comma_separated_table_is_still_read_as_before(tmp_path):
    path = tmp_path / "burden.csv"
    path.write_text(HEADER + ",".join(COLUMNS) + "\n" + "\n".join(",".join(map(str, r)) for r in ROWS) + "\n")
    assert [c.kind for c in read_wide_statistics(path).comparisons] == ["burden", "burden"]


def test_without_the_test_token_the_same_columns_are_an_ordinary_contrast(tmp_path):
    header = "".join(f"# {c}: control=gnomAD, treatment=probands\n" for c in COMPARISONS)
    table = read_wide_statistics(_burden_table(tmp_path / "t.tsv", header=header))
    assert [c.kind for c in table.comparisons] == ["contrast", "contrast"]
    assert table.comparisons[0].treatment == "probands"


@pytest.mark.parametrize("line, words", [
    ("# dominant_ptv: control=gnomAD, treatment=probands, test=burdne\n", "not a known test"),
    ("# dominant_ptv: probands against gnomAD, test=burden\n", "needs the comparison's control= and treatment="),
])
def test_a_test_token_that_cannot_be_honoured_is_refused(tmp_path, line, words):
    with pytest.raises(ProjectError) as err:
        read_wide_statistics(_burden_table(tmp_path / "t.tsv", header=line))
    assert err.value.code == 9 and words in str(err.value)


def test_a_burden_header_on_an_ftest_is_a_contradiction(tmp_path):
    path = tmp_path / "t.tsv"
    path.write_text("# X: control=gnomAD, treatment=probands, test=burden\n"
                    "gene_id\tX_F\tX_ANOVA_p\tX_ANOVA_q\nENSG00000000001\t2\t0.1\t0.2\n")
    with pytest.raises(ProjectError) as err:
        read_wide_statistics(path)
    assert err.value.code == 9 and "header says burden, columns say ftest" in str(err.value)


def test_both_fold_change_columns_or_neither_is_refused(tmp_path):
    both = tmp_path / "both.tsv"
    both.write_text("gene_id\tX_Fold_change\tX_Log2_fold_change\tX_P-value\tX_Q-value\n"
                    "ENSG00000000001\t2\t1\t0.01\t0.1\n")
    with pytest.raises(ProjectError) as err:
        read_wide_statistics(both)
    assert err.value.code == 6 and "give exactly one" in str(err.value)
    neither = tmp_path / "neither.tsv"
    neither.write_text("gene_id\tX_P-value\tX_Q-value\nENSG00000000001\t0.01\t0.1\n")
    with pytest.raises(ProjectError) as err:
        read_wide_statistics(neither)
    assert err.value.code == 6 and "X_Fold_change or X_Log2_fold_change" in str(err.value)


def test_half_a_pair_of_means_is_still_refused_beside_a_log2_column(tmp_path):
    path = tmp_path / "half.tsv"
