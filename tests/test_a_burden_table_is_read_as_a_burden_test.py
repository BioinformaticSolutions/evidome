"""A gene-burden table (probands against gnomAD) is an input like any other.

Paralome's DNA arm writes one tab-separated table: per model x tier, the log2 of
observed over expected carriers, a p and a q, and no group means. Its header says
``test=burden``. The table is read through the same crosswalk, enrichment,
regulators, report and figures as an expression table; the log2 column is taken
as log2 because it says so, never re-guessed from its values.
"""

